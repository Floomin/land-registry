/* Поширюємо відділення на всі КОАТУУ-варіанти в межах тієї самої ділянки
   (однакові перші 9 символів, різні останні символи) */
SELECT d.KOATUU, dep.Vidd, dep.Farm AS ExpectedFarm
INTO #new
FROM dbo.KoatuuDirectory d
JOIN #dept dep ON LEFT(d.KOATUU, 9) = LEFT(dep.KOATUU, 9);

-- Перевірка: чи не потрапив один КОАТУУ у дві різні групи одночасно (не мало б бути)
SELECT LEFT(KOATUU, 9) AS grp, COUNT(DISTINCT Vidd) AS variants
FROM #dept
GROUP BY LEFT(KOATUU, 9)
HAVING COUNT(DISTINCT Vidd) > 1;

-- Перевірка: де Farm у довіднику не збігається з очікуваною філією відділення
SELECT d.KOATUU, d.Farm AS Current_Farm, n.ExpectedFarm, n.Vidd
FROM dbo.KoatuuDirectory d
JOIN #new n ON n.KOATUU = d.KOATUU
WHERE d.Farm <> n.ExpectedFarm
ORDER BY d.KOATUU;

/* Що зміниться (перегляд) */
SELECT d.KOATUU, d.MainOrg, d.Farm, d.CouncilName,
       d.[Відділення] AS Old_Vidd,
       COALESCE(n.Vidd, N'Інформація відсутня') AS New_Vidd
FROM dbo.KoatuuDirectory d
LEFT JOIN #new n ON n.KOATUU = d.KOATUU
WHERE ISNULL(d.[Відділення], N'') <> COALESCE(n.Vidd, N'Інформація відсутня')
ORDER BY d.MainOrg, n.Vidd, d.KOATUU;

IF @Apply = 1
