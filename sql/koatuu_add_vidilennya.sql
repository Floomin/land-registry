    FROM dbo.KoatuuDirectory d
    LEFT JOIN #new n ON n.KOATUU = d.KOATUU
    WHERE ISNULL(d.[Відділення], N'') <> COALESCE(n.Vidd, N'Інформація відсутня');

    SELECT @@ROWCOUNT AS UpdatedRows;
END
